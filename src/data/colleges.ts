const deduped = new Map<string, CollegeRecord>();
for (const [name, city, district, category] of rows) {
  const key = name.toLowerCase().replace(/[^a-z0-9]/g, "");
  if (!deduped.has(key)) deduped.set(key, { name, city, district, category });
}
export const COLLEGE_DIRECTORY = Array.from(deduped.values()).sort((a, b) => a.name.localeCompare(b.name));

export function searchColleges(query: string, limit = 12) {
  const q = query.trim().toLowerCase();
  if (q.length < 2) return [];
  return COLLEGE_DIRECTORY.map((college) => {
    const name = college.name.toLowerCase();
    const city = college.city.toLowerCase();
    const district = college.district.toLowerCase();
    const score = name.startsWith(q) ? 0 : name.includes(q) ? 1 : city.startsWith(q) || district.startsWith(q) ? 2 : -1;
    return { college, score };
  }).filter((item) => item.score >= 0)
    .sort((a, b) => a.score - b.score || a.college.name.localeCompare(b.college.name))
    .slice(0, limit).map((item) => item.college);
}
